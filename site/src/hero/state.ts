/**
 * Общее состояние сцены.
 *
 * ТЗ 2.6: прогресс скролла пишется в один объект, который читают все системы —
 * шейдер, светлячки, звук. Отдельных подписок нет: их пришлось бы синхронизировать
 * между собой, а порядок обновления в кадре тогда становится случайным.
 */

export type Manifest = {
  canvas: { width: number; height: number; aspect: number };
  visibleFrame: { w: number; h: number };
  crops: Record<string, number>;
  planeBreaks: number[];
  planeParallax: { p1: number; p2: number; p3: number };
  travel: { camera_y: number; mouse_x: number; depth_bend: number };
  blurRadius: number;
  plateWidths: number[];
  /** формат форграунда: калька лежит в его альфе, поэтому только WebP */
  fogFormat: string;
  /** у кадров легенд свои ширины и только WebP: глубина лежит в альфе */
  legendWidths: number[];
  formats: string[];
  legends: { id: string; title: string; object: string; placeholder?: boolean }[];
};

export type Point = {
  id: string;
  title?: string;
  object?: string;
  canvas: [number, number];
  depth?: number;
  /** проценты кропа: кроп в пайплайне один, fullbleed 1.6:1 */
  fullbleed: [number, number];
};

/** Фазы сценария (ТЗ 1.5). Одна маска, разные роли. */
export const enum Phase {
  Fog = 0,      // экран 1, пятно ходит за курсором
  Reveal = 1,   // раскрытие: пятно на весь экран, параллакс включается
  Legends = 2,  // перелистывание легенд
}

export const state = {
  /** Прогресс скролла всей запиненной сцены, 0..1 */
  progress: 0,
  phase: Phase.Fog as Phase,
  /** нажата ли кнопка на экране входа: до этого сцена стоит закрытой */
  entered: false,
  /** какую кнопку выбрали на входе. Звука ещё нет, число ждёт его */
  sound: false,
  /**
   * 0..1 хода входа. Пока он нулевой, пятна нет вовсе и туман лежит на весь
   * экран — это и есть закрытая сцена под экраном входа. Отдельное число, а не
   * `reveal`: раскрытие по скроллу начинается уже после входа и работает по
   * своей шкале.
   */
  enter: 0,
  /** 0..1 внутри раскрытия */
  reveal: 0,
  /**
   * 0..1 хода изгиба по глубине. Своя шкала, длиннее раскрытия: мастер-кадр
   * обязан ещё двигаться в момент, когда снизу пойдёт первая легенда.
   */
  bend: 0,
  /**
   * 0..1 сборки меток в счётчик. Своя шкала, длиннее раскрытия: точки летят всю
   * дорогу до первой легенды, включая паузу по открытому кадру.
   */
  gather: 0,
  /** дробный индекс легенды в фазе 3: 1.4 = между второй и третьей */
  legend: 0,
  /** какая легенда назначена скроллом; −1 — пауза после раскрытия */
  legendIndex: -1,
  /** 0..1 — сколько прокручено внутри слота текущей легенды */
  legendLocal: 0,
  /** 0..1 — фронт наплыва; его рисует скролл в начале слота легенды */
  legendWipe: 0,
  /** 0..1 — насколько кадр легенды уже закрыл сцену (для гашения светлячков) */
  legendCover: 0,
  /** 0..1 — сколько прокручено внутри финального слота; 0 — лента легенд ещё идёт */
  outroLocal: 0,
  /** 0..1 — фронт наплыва финального экрана, той же природы, что у легенд */
  outroWipe: 0,
  /**
   * 0..1 — докуда снизу заливка финала легла гарантированно. Считается не по
   * фронту, а по его худшему случаю: у фронта есть языки и дыры, и ниже этой
   * отметки их не остаётся ни при каком шуме.
   *
   * Своего текста у финала больше нет — за наплывом сразу идёт страница, — но
   * число осталось замером: `check:legends` печатает его вместе с фронтом, и по
   * нему видно, дошла ли заливка до верха к концу слота.
   */
  outroRise: 0,
  /** курсор в UV экрана, 0..1 */
  pointer: { x: 0.5, y: 0.5 },
  /** курсор в -1..1 для параллакса */
  mouse: { x: 0, y: 0 },
  /** id точки под курсором или в фокусе */
  hover: null as string | null,
  /** идёт ли автономный дрейф (мышь стоит дольше 3.5 с) */
  idle: true,
  reduced: false,
  /** сколько точек уже загорелось, 0..1 */
  stagger: 0,
  time: 0,
  /** 0..1 — насколько активно сейчас двигают курсор, с быстрым затуханием */
  motion: 0,
  /** время маски: то же, что time, но под мышью бежит быстрее (ТЗ 1.2) */
  maskTime: 0,
};

export type State = typeof state;
