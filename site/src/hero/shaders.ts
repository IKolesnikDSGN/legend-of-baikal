/**
 * Шейдеры первого экрана.
 *
 * Вся картинка живёт в одном фуллскрин-кваде (ТЗ 2.2). Второй проход — только
 * светлячки: их нельзя мешать в первый, потому что рисуются они аддитивно и
 * каждый со своей мягкостью.
 *
 * Система координат одна на всё: **UV канваса**, включая поля. Плашки
 * экспортированы по канвасу именно поэтому — параллакс их разъезжает, и поля
 * закрывают края. Что из канваса видно, задаёт uFrame: центр и полуразмеры.
 */

export const QUAD_VERT = /* glsl */ `
  attribute vec2 uv;
  attribute vec2 position;
  varying vec2 vUv;
  void main() {
    vUv = uv;
    gl_Position = vec4(position, 0.0, 1.0);
  }
`;

/**
 * Пятно-маска: объявления и сама формула.
 *
 * Живёт отдельным куском, потому что считают её ДВА шейдера — сцена и снимок
 * маски для тёмной копии текста. Вторая формула для той же дыры разъедется в
 * первый же день, и текст начнёт перекрашиваться не там, где открылся кадр.
 */
export const MASK_GLSL = /* glsl */ `
  uniform sampler2D uNoise;         // R — крупная форма, G — мелкая рвань
  uniform float uAspect;            // ширина / высота вьюпорта
  uniform vec2  uBlob;              // положение пятна в UV экрана
  uniform float uRadius;            // радиус пятна в долях высоты экрана
  uniform float uNoiseAmp;          // 0 — пятно спокойное и круглое (магнетизм)
  uniform float uMaskTime;          // своё время маски: бежит быстрее под мышью
  uniform float uWarp;              // искажение координат: ломает силуэт целиком
  uniform vec2  uEdgeSoft;          // границы перехода: чем ближе, тем чётче край

  /**
   * 1 — туман на месте, 0 — кадр открыт.
   *
   * Сначала гнём саму систему координат и только потом меряем расстояние до
   * центра. Это принципиально: шум, добавленный к готовому расстоянию, лишь
   * обкусывает край — круг остаётся кругом с бахромой. Искажённая координата
   * ломает силуэт целиком, и от круга не остаётся ничего.
   *
   * Время у маски своё — uMaskTime, а не общее: оно бежит быстрее, пока курсор
   * движется. Множитель на общее время вместо этого рвал бы фазу шума при
   * каждом изменении скорости, и обрывки дёргались бы скачком.
   */
  float maskHole(vec2 suv) {
    vec2 w1 = vec2(
      texture2D(uNoise, suv * 1.15 + uMaskTime * vec2(0.021, -0.013)).r,
      texture2D(uNoise, suv * 1.15 + vec2(0.37, 0.61) - uMaskTime * vec2(0.017, 0.024)).g) - 0.5;
    vec2 w2 = vec2(
      texture2D(uNoise, suv * 3.30 - uMaskTime * vec2(0.033, 0.019)).g,
      texture2D(uNoise, suv * 3.30 + vec2(0.19, 0.83) + uMaskTime * vec2(0.026, 0.031)).r) - 0.5;
    // искажение в долях радиуса: пятно ломается одинаково и мелким, и раскрытым
    vec2 p = suv + (w1 + w2 * 0.45) * uWarp * uRadius;
    float d = length((p - uBlob) * vec2(uAspect, 1.0)) / max(uRadius, 1e-4);

    // Поверх — порог по двумерному полю, как у наплыва легенд: он добавляет
    // рваные языки и отдельные острова там, где искажение уже свернуло силуэт.
    float a = texture2D(uNoise, suv * vec2(2.20, 1.35) + uMaskTime * vec2(0.030, 0.018)).r;
    float b = texture2D(uNoise, suv * vec2(4.80, 3.10) - uMaskTime * vec2(0.047, 0.026)).g;
    float c = texture2D(uNoise, suv * vec2(9.50, 6.40) + uMaskTime * vec2(0.021, 0.038)).r;
    d += (a * 0.54 + b * 0.31 + c * 0.15 - 0.5) * uNoiseAmp;

    // Порог в пару пикселей: границы обрывков обязаны быть чёткими, всю форму
    // держит поле, а не растушёвка.
    return smoothstep(uEdgeSoft.x, uEdgeSoft.y, d);
  }
`;

/**
 * Снимок маски для тёмной копии текста.
 *
 * Рисует ровно ту же дыру, что и сцена, в маленький канвас: белое там, где
 * кадр открыт. Дальше картинка уходит в CSS как mask-image — по-другому форму
 * дыры в DOM не передать, а без неё второй цвет текста пришлось бы гадать
 * кругом, и он появлялся бы не там, где действительно светлый кадр.
 */
export const MASK_FRAG = /* glsl */ `
  precision highp float;
  varying vec2 vUv;
  ${MASK_GLSL}
  void main() {
    float hole = maskHole(vec2(vUv.x, 1.0 - vUv.y));
    gl_FragColor = vec4(1.0, 1.0, 1.0, 1.0 - hole);
  }
`;

export const SCENE_FRAG = /* glsl */ `
  precision highp float;

  varying vec2 vUv;                 // 0..1 по экрану

  ${MASK_GLSL}

  uniform sampler2D uP1;            // дальний план, непрозрачный
  uniform sampler2D uP2;            // средний план, с альфой
  uniform sampler2D uP3;            // ближний план, с альфой
  // Форграунд под маской: RGB — размытая копия канваса, A — покрытие кальки.
  // Один юнит на две карты по той же причине, что и у кадров легенд с глубиной:
  // восемь юнитов заняты все, девятой текстуры в WebGL1 может не быть вовсе.
  uniform sampler2D uFog;
  uniform sampler2D uDepth;         // R — глубина, G — эмиссия, B — калька в расфокусе

  // Оба цвета кальки приходят из токенов темы, а не живут числами в шейдере:
  // калька — это фон и выворотка, и они обязаны меняться вместе с палитрой.
  uniform vec3  uFogBg;             // фон форграунда, --bg тёмной темы
  uniform vec3  uFogInk;            // цвет форм, --fg-highlights
  uniform float uFogAlpha;          // плотность форм кальки
  uniform vec2  uFogTop;            // x — докуда сверху гаснут формы, y — что остаётся
  uniform float uFogBlur;           // докуда сверху калька уходит в расфокус
  uniform float uFogIn;             // вход: 0 — форм ещё нет, 1 — калька на месте
  uniform float uRim;               // подмес светлого в кромку кадра

  uniform vec4  uFrame;             // xy центр, zw полуразмеры в UV канваса
  uniform float uTime;

  uniform vec2  uSpot;              // светлячок под курсором, в UV экрана
  uniform float uSpotOn;            // 0..1 с лерпом: включение света от точки
  uniform float uSpotR;             // радиус светового пятна
  uniform vec3  uShadow;            // тень палитры, в чёрный уходить нельзя
  uniform float uFogMax;            // 1 в фазе 1, 0 после раскрытия

  uniform vec2  uMouse;             // -1..1, параллакс за курсором, с запаздыванием
  uniform vec2  uMouseAmp;          // амплитуда: y отрицателен, v растёт вверх
  uniform vec2  uPush;              // ход камеры: сдвиг, общий для всех планов
  uniform float uBend;              // амплитуда изгиба по глубине
  uniform vec3  uParallax;          // коэффициенты P1, P2, P3
  uniform float uReveal;            // 0..1 прогресс раскрытия
  uniform float uEmission;
  uniform float uEdge;              // ширина расфокуса по кромке, доля кадра

  // ── фаза 3: кадры легенд ─────────────────────────────────────────────────
  // Глубина каждого кадра лежит в его же альфе: в WebGL1 гарантированы восемь
  // текстурных юнитов, шесть уже заняты, на два слоя легенд отдельными картами
  // места нет.
  uniform sampler2D uUnder;         // легенда, которая уже наплыла целиком
  uniform sampler2D uOver;          // легенда, которая наплывает сейчас
  uniform float uUnderOn;           // 0 — под наплывом ещё мастер-кадр
  uniform float uOverOn;
  uniform float uWipe;              // 0..1 — положение фронта, снизу вверх
  uniform float uWipeSeed;          // своя рвань у каждой легенды
  uniform float uTear;              // разброс фронта по высоте: языки и острова
  uniform vec2  uLegendBend;        // изгиб по глубине: x — under, y — over
  uniform float uLegendInset;       // запас кадра под изгиб и параллакс
  uniform float uLegendDim;         // докуда уходит в тень нижний слой к концу наплыва
  uniform vec2  uSlide;             // подтяжка кадра вверх: x — under, y — over
  uniform float uDir;               // +1 — наплыв снизу вверх, −1 — сверху вниз

  // ── финальный экран ──────────────────────────────────────────────────────
  // За последней легендой тем же наплывом приходит не заливка, а прозрачность:
  // канвас открывается, и в дыру видно секцию страницы, которая всё это время
  // поднимается снизу обычным скроллом. Цвета у финала поэтому нет вовсе — его
  // приносит DOM.
  uniform float uOutro;             // 0..1 — фронт финального наплыва
  uniform float uOutroSeed;         // своё поле: за легендой с её рванью подряд

  // Экранные UV с началом СВЕРХУ. Курсор, светлячки и DOM живут в этой системе,
  // а геометрия квада отдаёт v снизу вверх — без пересчёта маска по вертикали
  // ходит навстречу мыши.
  vec2 screenUv() { return vec2(vUv.x, 1.0 - vUv.y); }

  /**
   * Кадр легенды: та же выборка, что у мастера, но глубина берётся из альфы
   * самой картинки, а окно поджато uLegendInset — за краем текстура тянется
   * последним пикселем, и изгиб размазал бы его полосой.
   */
  vec3 legendAt(sampler2D img, vec2 base, float bend, vec2 mouse, float slide) {
    vec2 b = 0.5 + (base - 0.5) * uLegendInset;
    vec4 t = texture2D(img, b);
    float far = 1.0 - t.a;
    // v растёт вверх (flipY): плюс по v опускает содержимое на экране, поэтому
    // недоехавший кадр стоит ниже своего места и поднимается к нулю
    vec2 uv = b + vec2(0.0, bend * far + slide) + mouse * far;
    return texture2D(img, uv).rgb;
  }

  /**
   * Фронт наплыва: снизу вверх, дырявый, но чёткий.
   *
   * Не смещённая линия, а порог по двумерному полю. Разница принципиальная:
   * сдвиг линии даёт рваную, но всё-таки одну кромку, а порог по полю рассыпает
   * фронт на языки и отдельные острова, которые проступают выше основной массы
   * и дорастают до неё. Именно так наплыв читается как проступающее изображение,
   * а не как штора.
   *
   * Поле сжато по горизонтали сильнее, чем по вертикали: пятна выходят шире,
   * чем выше, и не похожи на пузыри. Переход через порог — в один пиксель,
   * поэтому все края, и у фронта, и у островов, чёткие.
   *
   * Фронт и зерно приходят аргументами: тем же наплывом за последней легендой
   * идёт финальный экран, и вторая формула для той же кромки разъехалась бы с
   * этой на первой же правке.
   */
  float dissolveWipe(vec2 suv, float wipe, float s) {
    float a = texture2D(uNoise, suv * vec2(1.10, 0.62) + vec2(s, uTime * 0.010)).r;
    float b = texture2D(uNoise, suv * vec2(2.40, 1.35) - vec2(s, uTime * 0.017)).g;
    float c = texture2D(uNoise, suv * vec2(5.20, 2.90) + vec2(s * 2.0, uTime * 0.024)).r;
    float field = a * 0.56 + b * 0.30 + c * 0.14;      // 0..1

    // Отсчёт идёт от той кромки, с которой заходит наплыв: вниз по странице —
    // снизу вверх, вверх по странице — сверху вниз. Иначе отмотка назад
    // проигрывает то же движение, что и вперёд, и скролл теряет направление.
    float h = uDir > 0.0 ? 1.0 - suv.y : suv.y;
    float v = h - (field - 0.5) * uTear;
    // запас на амплитуду поля: иначе на uWipe = 0 самые «лёгкие» острова уже
    // видны, а на 1 у верхней кромки остаются прорехи
    float line = mix(-uTear * 0.55, 1.0 + uTear * 0.55, wipe);
    const float AA = 0.0015;                           // ~1.4 px на экране 900
    return 1.0 - smoothstep(line - AA, line + AA, v);
  }

  void main() {
    // Кадр всегда во весь экран: сколько канваса влезает, задаёт uFrame,
    // раскрытие меняет только охват — от тесного плана к целой сцене.
    vec2 base = uFrame.xy + (vUv - 0.5) * uFrame.zw * 2.0;

    // глубина берётся один раз по базовой точке: сдвигать выборку глубины вместе
    // с плашкой смысла нет, а лишняя зависимость дала бы дрожание на краях
    vec2 dm = texture2D(uDepth, base).rg;
    float depth = dm.r;
    float emis  = dm.g;
    float far = 1.0 - depth;          // 1 у горизонта, 0 у ближнего края кадра

    // Ход планов: вычитание по Y опускает картинку вниз. Дальний план идёт
    // вниз быстрее ближнего — коэффициенты приходят из конфига пайплайна.
    vec2 drift = -uPush;

    // Изгиб по глубине. Вертикаль здесь считается от НИЗА кадра: текстуры
    // грузятся с flipY, и v растёт вверх. Поэтому «уехать вниз» — это увеличить
    // v: выборка берётся выше по картинке, а на экране содержимое опускается.
    vec2 bend  = vec2(0.0, uBend * far);
    // параллакс за мышью тоже по глубине: дальнее ходит сильнее
    vec2 mouse = uMouse * uMouseAmp * far;

    vec2 uv1 = base + drift * uParallax.x + bend + mouse;
    vec2 uv2 = base + drift * uParallax.y + bend + mouse;
    vec2 uv3 = base + drift * uParallax.z + bend + mouse;

    vec3 plate1 = texture2D(uP1, uv1).rgb;
    vec4 plate2 = texture2D(uP2, uv2);
    vec4 plate3 = texture2D(uP3, uv3);
    vec3 sharp = mix(mix(plate1, plate2.rgb, plate2.a), plate3.rgb, plate3.a);

    // Форграунд идёт по той же выборке, что и резкий кадр: тот же изгиб по
    // глубине, тот же параллакс за курсором. Иначе на краю маски контур
    // разъезжается со своим объектом, а край здесь шириной в пиксель.
    vec4 fogTex = texture2D(uFog, base + bend + mouse);
    // размытая копия из того же файла — ею уходит в расфокус кромка кадра
    vec3 blurred = fogTex.rgb;

    // ── маска-пятно ──────────────────────────────────────────────────────────
    vec2 suv = screenUv();

    // Калька: плоский фон темы и белые формы, без полутонов между ними. Верх
    // кадра тонет в чистом фоне — там стоят заголовок и хедер, и дальние гряды
    // под ними спорят с текстом. Растворение идёт по экрану, а не по картинке:
    // граница отмерена от кромки экрана, до неё же и относится.
    // Приглушены сами формы, а не слой целиком: фон обязан остаться плоским.
    // Смешивать кальку с кадром нельзя — сквозь неё полезет светлый туман, и
    // ровный фон станет градиентом от неба.
    float top = 1.0 - smoothstep(0.0, uFogTop.x, suv.y);

    // Верх кальки ещё и расфокусирован — тем сильнее, чем ближе к кромке, и до
    // нуля к первой гряде верхушек. Размытый уровень приходит готовым, синим
    // каналом карты глубины: считать его выборками в шейдере нельзя, на тонком
    // контуре десяток выборок читается веером призраков, а не размытием.
    // Промежуточная сила — смешивание резкой кальки с этим уровнем.
    float soft = 1.0 - smoothstep(0.0, uFogBlur, suv.y);
    // Вход: формы проступают из расфокуса и из прозрачности разом. Расфокус —
    // тот же готовый уровень, что держит верх кадра, поэтому лишних выборок
    // проявление не стоит: на входе он просто взят на весь экран.
    soft = max(soft, 1.0 - uFogIn);
    float cover = mix(fogTex.a, texture2D(uDepth, base + bend + mouse).b, soft);

    float ink = cover * uFogAlpha * mix(1.0, uFogTop.y, top) * uFogIn;
    vec3 stencil = mix(uFogBg, uFogInk, ink);

    // Форма дыры считается общей функцией: ту же самую маску снимает в картинку
    // textmask.ts, и тёмная копия текста обязана перекраситься ровно там, где
    // открылся кадр. Сателлитов больше нет — отстающие мелкие пятна читались
    // как вторая маска, тянущаяся за первой, а не как «туман здесь реже».
    float hole = maskHole(suv);
    // Дыра открывается до конца. У размытой копии внутри пятна оставалось 15%:
    // полностью резкая дыра читалась прожектором. У кальки остаток так не
    // работает — контур лёг бы поверх своего же объекта второй линией.
    float fog = hole * uFogMax;

    vec3 color = mix(sharp, stencil, fog);
    // источники света пробиваются сквозь форграунд сильнее остальной картинки
    color += emis * fog * uEmission;

    // Кромка кадра уходит в расфокус. Камера отъезжает дальше видимого кадра —
    // в полях лежит дорисованная моделью заливка, и держать её резкой нельзя:
    // это не композиция, а материал. Размытая, она читается как продолжение
    // тумана, а не как край картинки.
    float e = uEdge;
    float edge = smoothstep(0.0, e, vUv.x) * smoothstep(1.0, 1.0 - e, vUv.x)
               * smoothstep(0.0, e, vUv.y) * smoothstep(1.0, 1.0 - e, vUv.y);
    // Кромка — размытое продолжение самого кадра, а не рамка. Тень из него
    // убрана (копия больше не тонируется), и к самому краю добавляется немного
    // света: чистая размытая копия у внутренней границы, чуть светлее у кромки.
    // Резкий подмес белого давал ровно то, чего быть не должно, — обрыв кадра
    // в белое поле, поэтому сила идёт по квадрату, а не прямой.
    //
    // Смешивается кромка по МЕСТНОЙ маске, а не по фазе: под калькой она
    // уходит в кальку (светлая рамка по её краю читалась бы браком), а там, где
    // пятно открыло кадр, — в светлое. По фазе выходило, что в тумане кромка
    // всегда тёмная, и пятно, доехавшее до края экрана, упиралось в полосу фона.
    float lift = 1.0 - edge;
    vec3 rim = mix(mix(blurred, uFogInk, uRim * lift * lift), stencil, fog);
    color = mix(rim, color, edge);

    // ── свет от точки под курсором ───────────────────────────────────────────
    // Наведение на светлячок не просто открывает окно в тумане, а зажигает свой
    // огонь: вокруг него кадр подсвечивается, всё остальное уходит в тень
    // палитры. Считается после кромки, чтобы притемнение легло на весь экран
    // ровно, без светлого ободка по краю.
    if (uSpotOn > 0.001) {
      float sd = length((suv - uSpot) * vec2(uAspect, 1.0)) / max(uSpotR, 1e-4);
      float glow = exp(-2.2 * sd * sd);
      // осветление пропорционально самому пикселю: небо не выбивается в белое,
      // а огни на берегу разгораются
      vec3 near = color * (1.0 + 0.34 * glow);
      vec3 far  = mix(color, uShadow, 0.48);
      color = mix(color, mix(far, near, glow), uSpotOn);
    }

    // ── фаза 3: легенды наплывают маской ─────────────────────────────────────
    // Слоёв всегда ровно два, и любой из них может быть мастер-кадром. Это не
    // частный случай, а то же самое смешивание: наверх по странице от первой
    // легенды мастер наплывает обратно ровно так же, как легенда наплывала на
    // него. Всё, что глубже двух слоёв, накрыто целиком и в кадр не попадает.
    // Ветка по юниформам, одинаковая для всего кадра: в фазах 1–2 легенд нет
    // вообще, и три выборки поля наплыва там платить не за что.
    if (uUnderOn + uOverOn > 0.5) {
      vec2 mouseAmp = uMouse * uMouseAmp;
      vec3 master = color;
      vec3 lower = uUnderOn > 0.5 ? legendAt(uUnder, base, uLegendBend.x, mouseAmp, uSlide.x) : master;
      vec3 upper = uOverOn > 0.5 ? legendAt(uOver, base, uLegendBend.y, mouseAmp, uSlide.y) : master;
      // Уходящий слой отступает в тень по мере наплыва. Два одинаково ярких
      // изображения в один момент спорят за внимание, и фронт читается швом
      // между ними, а не проступающей картинкой. Тень палитры, а не чёрный:
      // кадр обязан остаться в рампе. Мастер здесь такой же нижний слой, как
      // легенда, поэтому первая легенда гасит его тем же кодом.
      // Гаснет по корню, а не прямой: на прямой уходящий кадр держит полную
      // яркость ровно там, где фронт только пошёл, — то есть весь тот участок,
      // где на него ещё смотрят. Тень обязана опережать фронт.
      lower = mix(lower, uShadow, sqrt(uWipe) * uLegendDim);
      color = mix(lower, upper, dissolveWipe(suv, uWipe, uWipeSeed));
    }

    // ── финальный экран ──────────────────────────────────────────────────────
    // За последней легендой той же маской открывается страница: там, где фронт
    // прошёл, канвас становится прозрачным, и под ним видно секцию «О
    // территории» — она весь финальный слот поднимается снизу обычным скроллом.
    // Заливки цветом здесь больше нет: рисовать фон следующего блока значит
    // держать его цвет вторым числом рядом с токеном темы, а под дырой лежит и
    // сам этот фон, и текст на нём.
    //
    // Уходящая легенда гаснет тем же движением, что и любой нижний слой: она
    // такой же нижний слой и есть.
    float outro = 0.0;
    if (uOutro > 0.001) {
      color = mix(color, uShadow, sqrt(uOutro) * uLegendDim);
      outro = dissolveWipe(suv, uOutro, uOutroSeed);
    }

    gl_FragColor = vec4(color, 1.0 - outro);
  }
`;

/**
 * Точки-легенды. Инстансный квад на точку: позиция приходит в UV канваса и
 * проходит ту же цепочку параллакса, что и плашка соответствующего плана, —
 * иначе точка отклеится от своего огня на первом же движении камеры.
 *
 * Это метки, а не светлячки: плотный кружок акцентного цвета с чётким краем.
 * Туман их не глушит — они и есть то, за чем пришли, и в дефолте обязаны
 * читаться. Размывается и уменьшается точка ровно под курсором: наведение
 * уводит внимание с метки на сам огонь, который она отмечала.
 *
 * Вокруг метки расходится кольцо-радар, и на раскрытии все метки слетаются в
 * одну точку — место счётчика собранных легенд. Оба движения живут здесь, а не
 * в DOM: метка едет вместе со своим планом, и второй слой поверх канваса
 * отставал бы от неё на кадр.
 */
export const FIREFLY_VERT = /* glsl */ `
  attribute vec2 position;          // квад -1..1
  attribute vec2 aPos;              // ГОТОВАЯ позиция в UV экрана
  attribute vec3 aSeed;             // фаза пульса, период, орбита
  attribute float aKind;            // 1 — точка-легенда, 0 — фон
  attribute float aCold;            // 1 — эпишура: ровнее остальных
  attribute float aHot;             // 0..1 с лерпом: точка под курсором

  uniform float uAspect;
  uniform float uTime;
  uniform float uSize;              // базовый размер в долях высоты экрана
  uniform vec2  uAttract;           // активная точка, к ней стягивается фон
  uniform float uAttractOn;
  uniform float uFade;              // 0 — кадр легенды накрыл сцену целиком
  uniform vec2  uHover;             // x — насколько ужимается, y — мягкость края
  uniform vec3  uRing;              // радар: докуда уходит, толщина, яркость
  uniform vec2  uGather;            // куда слетаются метки, UV экрана
  uniform vec2  uGatherAmt;         // x — 0..1 сборка, y — разброс по времени

  varying float vGlow;
  varying vec2  vQuad;
  varying float vSoft;
  varying float vRing;              // 0..1 ход волны радара
  varying float vRingOn;

  void main() {
    // Позиция приходит уже в экранных UV. Считает её CPU той же функцией, что
    // ставит DOM-кнопки: две формулы для одного и того же места неизбежно
    // разъезжаются, и точка уходит от своего огня.
    vec2 screen = aPos;

    // лёгкий дрейф по орбите: своя фаза у каждого, синхронное движение читается
    // как техническая ошибка
    float t = uTime * aSeed.y + aSeed.x * 6.2831;
    screen += vec2(cos(t), sin(t * 0.7)) * aSeed.z;

    if (aKind < 0.5 && uAttractOn > 0.5) {
      screen = mix(screen, uAttract, 0.25 * (0.5 + 0.5 * sin(t)));
    }

    // Сборка: на раскрытии метки слетаются в одну точку — на место счётчика
    // собранных легенд. Своя задержка у каждой: шесть точек, стартующих разом,
    // читаются строем, а не тем, что кадр их забирает с собой.
    float lag = aSeed.x * uGatherAmt.y;
    float g = clamp((uGatherAmt.x - lag) / max(1.0 - lag, 1e-4), 0.0, 1.0);
    g = g * g * (3.0 - 2.0 * g);
    screen = mix(screen, uGather, g);

    // Пульс. Период у каждой свой и не кратен соседнему: на одинаковых
    // периодах шесть точек через полминуты сходятся в такт и начинают мигать
    // хором. Эпишура пульсирует вдвое спокойнее — она не огонь на берегу.
    float beat = uTime * (0.7 + aSeed.y * 0.9) + aSeed.x * 6.2831;
    float amp = mix(0.10, 0.05, aCold) * (1.0 - aHot) * (1.0 - g);
    float pulse = 1.0 + amp * sin(beat);
    // Метка непрозрачна с первого кадра. Очереди зажигания больше нет: она была
    // нужна светящейся точке, которая проступала из тумана, а мишень, которая
    // разгорается, читается как ещё не готовая к нажатию.
    vGlow = (aKind > 0.5 ? 1.0 : 0.10) * uFade;
    // край: в покое режется в пиксель, под курсором расплывается
    vSoft = mix(0.03, uHover.y, aHot);

    // Радар идёт по тому же счёту, что и пульс: волна рождается на его подъёме,
    // а не сама по себе, и метка читается одним биением, а не двумя. Под
    // курсором и у собранных меток кольца нет: там оно рябь, а не отклик.
    vRing = fract(beat / 6.2831);
    vRingOn = (aKind > 0.5 ? 1.0 : 0.0) * uFade * (1.0 - aHot) * (1.0 - g);

    float size = uSize * (aKind > 0.5 ? 1.0 : 0.22) * pulse * mix(1.0, uHover.x, aHot);
    // Квад метки расширен под кольцо: оно уходит за её край, и обрезать его
    // нечем. vQuad остаётся в радиусах самой метки — 1.0 всегда её кромка.
    float span = aKind > 0.5 ? uRing.x : 1.0;
    vQuad = position * span;
    vec2 clip = (screen * 2.0 - 1.0) * vec2(1.0, -1.0);
    gl_Position = vec4(clip + position * size * span * vec2(1.0 / uAspect, 1.0), 0.0, 1.0);
  }
`;

export const FIREFLY_FRAG = /* glsl */ `
  precision highp float;
  varying float vGlow;
  varying vec2  vQuad;
  varying float vSoft;
  varying float vRing;
  varying float vRingOn;

  uniform vec3 uDot;                // цвет метки, --accent тёмной темы
  uniform vec3 uRing;               // радар: докуда уходит, толщина, яркость

  void main() {
    float r = length(vQuad);
    // Плоский круг с чётким краем. Ширина перехода — vSoft: в покое это
    // сглаживание в пиксель, под курсором — то самое размытие.
    float a = (1.0 - smoothstep(1.0 - vSoft, 1.0, r)) * vGlow;

    // Кольцо-радар: отходит от самой кромки метки, расширяется и гаснет.
    // Затухание по степени, а не линейное: линейное держит кольцо видимым почти
    // до конца хода, и оно читается вторым контуром, а не следом. Рождение тоже
    // не мгновенное — иначе на кромке метки каждый такт вспыхивает ободок.
    float rr = mix(1.0, uRing.x, vRing);
    float life = pow(1.0 - vRing, 1.5) * smoothstep(0.0, 0.12, vRing);
    float ring = (1.0 - smoothstep(0.0, uRing.y, abs(r - rr))) * life * uRing.z * vRingOn;
    a += ring * (1.0 - a);

    if (a < 0.004) discard;
    gl_FragColor = vec4(uDot, a);
  }
`;
