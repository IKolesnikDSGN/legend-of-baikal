/**
 * Свободное поле кадра — полоса между текстом первого экрана и подписью к карте.
 *
 * Метки легенд и мини-плашка живут в нём и только в нём. Заголовок, дивайдер и
 * подписи стоят вывороткой прямо поверх кадра, и метка, попавшая на строку,
 * читается не мишенью, а помаркой: у неё тот же акцентный цвет, что у ссылки
 * рядом, и та же плотность, что у полужирной подписи.
 *
 * Кромки меряются у самой разметки, а не берутся числами. Текст набран
 * текучими токенами и занимает долю высоты, которая гуляет вдвое: замер по
 * нижней кромке подписей — 37% высоты экрана на 1280×720 против 21% на
 * 1024×1366. Вписанная сюда доля разъехалась бы с первой же правкой шкалы,
 * причём молча — сцена о ней не узнает.
 *
 * Место назначает DOM, а не сцена: ровно тем же порядком, каким плашка
 * счётчика отдаёт сцене свой `target` (`tally.ts`). Сцена спрашивает поле и
 * опускает под него кадр; мини-плашка держится того же поля.
 */

export class Field {
  /** Доли высоты экрана: докуда сверху доходит текст и откуда снизу подпись. */
  top = 0;
  bottom = 1;

  constructor(
    private intro: HTMLElement,
    private map: HTMLElement,
  ) {
    this.measure();
  }

  /**
   * Кромки — прямоугольники разметки. Вход строк идёт `transform`, а он в
   * раскладку не попадает вовсе: к первому наведению ход давно кончился, а на
   * resize — тем более.
   */
  measure() {
    const h = window.innerHeight || 1;
    this.top = this.intro.getBoundingClientRect().bottom / h;
    this.bottom = this.map.getBoundingClientRect().top / h;
  }
}
