/**
 * Скролл-сценарий (ТЗ 1.5, 2.6).
 *
 * Секция пинится, длина скролла задана явно, прогресс пишется в общее состояние.
 * Скролл-хайджекинга нет: Lenis добавляет инерцию, но не меняет привычную скорость
 * колеса, и pin не мешает уйти со сцены вниз.
 *
 * Таймлайн задан **в экранах, а не в долях**: доли пришлось бы пересчитывать
 * руками при каждом изменении числа легенд, и они молча разъезжались бы с длиной
 * пина. Экраны складываются в длину и тут же делятся обратно в доли.
 *
 *   раскрытие ─── пауза ─── легенда 1 ─── легенда 2 ─── … ─── легенда 6 ─── финал
 *
 * Пауза после раскрытия обязательна по 1.5: маска дошла до края экрана, кадр
 * открыт целиком, и его нужно успеть увидеть до того, как снизу поедет первая
 * легенда. Без неё раскрытие и наплыв слипаются в одно движение.
 */

import gsap from 'gsap';
import ScrollTrigger from 'gsap/ScrollTrigger';

import { initSmooth, onSmoothScroll, startSmooth, stopSmooth } from '../lib/smooth';
import { Phase, state } from './state';

/** экран на раскрытие маски */
const REVEAL_SCREENS = 1;
/** сколько «ещё немножко» проматывается по открытому кадру до первой легенды */
const HOLD_SCREENS = 0.5;
/**
 * Экранов на легенду. Скролл отмеряет, сколько легенда живёт, и всё это время
 * карточка ползёт снизу вверх, а кадр за ней подтягивается — иначе слот стоит
 * на месте и читается как зависший пин. Было 2 экрана, сокращено на треть:
 * лента из шести легенд по два экрана растягивала пин почти на 14 экранов.
 *
 * Наплыв тоже идёт по скроллу: первые `WIPE_SHARE` слота (scene.ts) — фронт
 * маски, остальное легенда стоит. Ничего своего сцена при этом не считает,
 * поэтому переход обратим: отмотка уводит тот же фронт назад.
 */
const LEGEND_SCREENS = 1.35;
/**
 * Финальный экран за последней легендой: той же маской открывается страница, и
 * на этом запиненная сцена кончается.
 *
 * Экран ровно один, и это не «на глаз»: за него секция под сценой проезжает свой
 * экран снизу вверх и встаёт по верхней кромке ровно к концу пина (перекрытие
 * ставит `overlap` ниже). Дай финалу полтора экрана — и пин отпустит секцию не
 * там, где она доехала, то есть скачком.
 *
 * Наплыв занимает слот целиком (`WIPE_SHARE` к нему не применяется — см.
 * `advanceLegends`): пауза здесь была бы остановкой на ровном месте — стоять
 * после наплыва нечему, дальше идёт та же страница тем же скроллом.
 */
const OUTRO_SCREENS = 1;
/**
 * Хвост изгиба по глубине: он доигрывает всю паузу и заходит на первый экран
 * легенды, потому что наплыв обязан начаться, пока мастер-кадр ещё движется. По
 * статичной картинке первая легенда поднимается как по обоям.
 *
 * Хвост — это **перебор сверх** раскрытия, а не растянутый на него ход. Растянув
 * ход, изгиб к концу раскрытия набирал только половину амплитуды, и деформация
 * на самом раскрытии — там, где её и смотрят, — заметно слабела. Здесь к концу
 * раскрытия амплитуда ровно та, что была, а лишние 20% приходятся на паузу и
 * вход первой легенды, то есть на кадры, которые наплыв уже накрывает.
 */
const BEND_TAIL_SCREENS = 0.6;
const BEND_TAIL_GAIN = 0.2;
/**
 * Сборка меток в счётчик идёт весь путь до первой легенды, а не по раскрытию:
 * доля здесь — от участка «раскрытие + пауза». По шкале раскрытия точки
 * слетались почти мгновенно, стоило крутить колесо с обычной скоростью.
 *
 * 0.9, а не 1: собранная точка обязана постоять кругом хоть мгновение до того,
 * как первая легенда развернёт её в плашку со счётом. Сойдись эти два события
 * в один кадр — сборка прочиталась бы не сборкой, а появлением плашки.
 */
const GATHER_SHARE = 0.9;

export type Scroll = { destroy(): void; stop(): void; start(): void };

const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v);
/** сглаживание концов: линейная сборка стартует и тормозит рывком */
const smooth01 = (v: number) => v * v * (3 - 2 * v);

export function initScroll(
  section: HTMLElement,
  legendCount: number,
  onLegend: (index: number, fraction: number) => void,
  reduced: boolean,
  overlap: boolean,
): Scroll {
  gsap.registerPlugin(ScrollTrigger);

  /**
   * Перекрытие: секция под сценой поднимается на высоту сцены вверх и весь
   * финальный слот едет снизу обычным скроллом, а маску для неё рисует сцена —
   * фронт наплыва снимает канвас в прозрачность. Без перекрытия последний экран
   * пина был бы пустым: заливка легла, а страница всё ещё ниже кромки.
   *
   * Величина — ровно высота пиннутой секции, и она же обязана быть длиной
   * финального слота: пин отпускает через `screens` экранов, и секция окажется
   * по верхней кромке только если поднята ровно на свой экран. Число живёт в CSS
   * первого экрана (`--hero-h`), отсюда приходит только разрешение.
   *
   * Ставится ДО подъёма пина: атрибут меняет высоту документа, а пересчёт границ
   * после — это перестановка узлов, которая обрывает запущенные переходы.
   *
   * Только для WebGL-сцены: без неё канвасу нечем открыться, и наехавшая секция
   * просто накрыла бы статичный кадр без всякого перехода.
   */
  if (overlap) document.documentElement.dataset.heroOverlap = '';

  /**
   * Прокрутка общая на страницу (`lib/smooth.ts`), сцена её не создаёт: инерция
   * обязана работать и там, где первого экрана нет. Отсюда только подписка —
   * Lenis доводит прокрутку инерцией и после последнего события колеса, а пин
   * обязан пересчитаться на каждом её кадре.
   */
  const offSmooth = reduced ? () => {} : (initSmooth(), onSmoothScroll(ScrollTrigger.update));

  const screens =
    REVEAL_SCREENS + HOLD_SCREENS + LEGEND_SCREENS * legendCount + OUTRO_SCREENS;
  const revealShare = REVEAL_SCREENS / screens;
  const legendsFrom = (REVEAL_SCREENS + HOLD_SCREENS) / screens;
  const slot = LEGEND_SCREENS / screens;
  const outroFrom = legendsFrom + slot * legendCount;
  const outroSlot = OUTRO_SCREENS / screens;
  const bendShare = (REVEAL_SCREENS + HOLD_SCREENS + BEND_TAIL_SCREENS) / screens;

  const trigger = ScrollTrigger.create({
    trigger: section,
    start: 'top top',
    end: `+=${screens * 100}%`,
    pin: true,
    pinSpacing: true,
    scrub: true,
    onUpdate: (self) => {
      const p = self.progress;
      state.progress = p;
      state.reveal = Math.min(1, p / revealShare);
      state.bend = p <= revealShare
        ? p / revealShare
        : 1 + BEND_TAIL_GAIN * Math.min(1, (p - revealShare) / (bendShare - revealShare));
      // светлячки загораются по очереди по мере раскрытия
      state.stagger = Math.min(1, (p / revealShare) * 1.3);
      // метки слетаются в счётчик: движение начинается вместе с отъездом кадра
      // и длится до первой легенды — свой отрезок таймлайна, не шкала раскрытия
      state.gather = smooth01(clamp01(p / (legendsFrom * GATHER_SHARE)));
      // финальный слот: сам фронт из этой доли выводит сцена — той же долей
      // слота, что и у легенд, и своим сглаживанием
      state.outroLocal = clamp01((p - outroFrom) / outroSlot);

      if (p < revealShare * 0.04) state.phase = Phase.Fog;
      else if (p < legendsFrom) state.phase = Phase.Reveal;
      else state.phase = Phase.Legends;

      // положение внутри ленты легенд: 1.4 — вторая легенда, прокручена на 40%
      const t = (p - legendsFrom) / slot;
      state.legend = Math.max(0, t);

      if (t < 0) {
        state.legendIndex = -1;
        state.legendLocal = 0;
        onLegend(-1, 0);
        return;
      }

      const index = Math.min(legendCount - 1, Math.floor(t));
      state.legendIndex = index;
      state.legendLocal = clamp01(t - index);
      onLegend(index, state.legendLocal);
    },
  });

  return {
    /** Пауза прокрутки, пока держит экран входа. Обоснование — в `lib/smooth.ts`. */
    stop() {
      stopSmooth();
    },
    start() {
      startSmooth();
    },
    /**
     * Уходит пин и подписка, но не сама прокрутка: экземпляр общий на страницу,
     * и убив его здесь, сцена забрала бы инерцию у всех блоков ниже.
     */
    destroy() {
      delete document.documentElement.dataset.heroOverlap;
      trigger.kill();
      offSmooth();
      ScrollTrigger.getAll().forEach((t) => t.kill());
    },
  };
}
