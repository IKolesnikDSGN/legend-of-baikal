/**
 * Съёмка территории → форматы для веба.
 *
 * Исходник приходит с дрона: 4K, 50 кадров, HEVC 10 бит, сотни мегабайт. В
 * репозиторий он не едет (`.gitignore`), в браузер — тем более. Этот скрипт и
 * есть та стадия, которая делает из него веб-версию: руками в `public/media/`
 * не кладётся ничего, как и в остальном проекте.
 *
 *   node scripts/video.mjs ../DJI_20260725145805_0005_D.MP4 territory
 *
 * Пишет рядом с именем: два кодека и две ширины плюс постер.
 *   <name>-1600.mp4 / .webm   — одна ширина на все экраны (почему — ниже)
 *   <name>-poster.webp        — первый кадр: стоит, пока видео не поехало
 *
 * H.264 берут все браузеры, VP9 — Chrome и Firefox, и он же легче примерно на
 * треть; порядок <source> в разметке решает, кому что достанется. 25 кадров
 * вместо 50: это фоновая панорама, а не спорт, и половина кадров здесь стоит
 * ровно половину веса. Звука у исходника нет вовсе, поэтому дорожка снимается
 * явно (-an) — пустая дорожка в MP4 мешает автоплею на iOS.
 *
 * Все числа — здесь: вторая копия в другом месте разъедется с этой молча.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, statSync } from 'node:fs';

const [src, name = 'territory'] = process.argv.slice(2);
if (!src) {
  console.error('нужен путь к исходнику: node scripts/video.mjs <file> [name]');
  process.exit(1);
}

const OUT = new URL('../public/media/', import.meta.url);
mkdirSync(OUT, { recursive: true });

/** Ширина вывода одна, и это решение, а не экономия. У `<video>` нет `srcset`:
    атрибут `media` у `<source>` браузеры не читают вовсе (в отличие от
    `<picture>`), поэтому выбор ширины пришлось бы делать скриптом — и тогда без
    скрипта не играло бы ничего, а с ним первый запрос уходил бы ещё до подмены.
    1600 — компромисс, который видно в замере: на 1440 бокс шире кадра всего на
    10%, а на телефоне лишний вес в пределах мегабайта. Высота считается по
    пропорции исходника (-2 — кратность двум, её требуют оба кодека). */
const WIDTHS = [1600];
/** Кадров в секунду на выходе. */
const FPS = 25;
/** Качество. H.264 и VP9 считают CRF по-разному, поэтому числа разные, а
    результат сопоставимый. */
const CRF = { mp4: { 1600: 24 }, webm: { 1600: 33 } };

/** Цвет исходника (bt709) прописывается в выход явно: без этого Safari красит
    перекодированный кадр по своему усмотрению, и панорама уходит в зелень. */
const COLOR = ['-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'bt709'];

/** Тон. Дрон снимает в плоском профиле — тени подняты, света прижаты, цвет
    обесцвечен, и в браузере это читается не «дымкой над Байкалом», а серым
    кадром рядом с насыщенной сценой первого экрана. Числа сняты замером самого
    файла (`signalstats` по каждому сотому кадру, шкала 10 бит): чёрная точка
    стоит на 217–296 вместо 64, белая на 812 вместо 940, насыщенность 9.9 при
    типичных для bt709 20–40.

    Кривая растягивает ровно этот диапазон и ничего не выдумывает: 0.21 → 0.02
    и 0.79 → 0.96 — это и есть измеренные кромки, приведённые к полной шкале,
    середина остаётся на месте. Насыщенность добирается отдельным множителем,
    потому что кривая на неё не влияет вовсе.

    Это стадия, а не «поправил на глаз в редакторе»: числа лежат здесь, правка
    повторяется одной командой. Придёт цветокоррекция от заказчика — снимается
    вместе с этой строкой. */
const GRADE = "curves=all='0/0 0.21/0.02 0.53/0.5 0.79/0.96 1/1',eq=saturation=1.5";

const run = (args) => execFileSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', ...args]);
const size = (f) => `${(statSync(new URL(f, OUT)).size / 1e6).toFixed(1)} МБ`;

for (const w of WIDTHS) {
  const vf = `scale=${w}:-2:flags=lanczos,fps=${FPS},${GRADE}`;

  run(['-i', src, '-map', '0:v:0', '-vf', vf, '-c:v', 'libx264', '-profile:v', 'high',
    '-pix_fmt', 'yuv420p', '-crf', String(CRF.mp4[w]), '-preset', 'slow',
    ...COLOR, '-movflags', '+faststart', '-an', new URL(`${name}-${w}.mp4`, OUT).pathname]);

  run(['-i', src, '-map', '0:v:0', '-vf', vf, '-c:v', 'libvpx-vp9',
    '-pix_fmt', 'yuv420p', '-crf', String(CRF.webm[w]), '-b:v', '0', '-row-mt', '1',
    ...COLOR, '-an', new URL(`${name}-${w}.webm`, OUT).pathname]);

  console.log(`${name}-${w}.mp4  ${size(`${name}-${w}.mp4`)}`);
  console.log(`${name}-${w}.webm ${size(`${name}-${w}.webm`)}`);
}

/** Постер — первый кадр в полной ширине вывода: он стоит в боксе, пока видео не
    поехало, и при `prefers-reduced-motion` остаётся вместо него насовсем. */
run(['-i', src, '-map', '0:v:0', '-vf', `scale=${WIDTHS[0]}:-2:flags=lanczos,${GRADE}`,
  '-frames:v', '1', '-c:v', 'libwebp', '-quality', '82',
  new URL(`${name}-poster.webp`, OUT).pathname]);
console.log(`${name}-poster.webp ${size(`${name}-poster.webp`)}`);
